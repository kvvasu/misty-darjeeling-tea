/**
 * §3.4 — CSP hash automation. Computes the SHA-256 hash of the inline theme
 * script (app/theme-script.ts THEME_SCRIPT) and writes:
 *
 *   1. public/_headers   — full header set (host-portability artifact; GitHub
 *                          Pages does NOT serve custom HTTP headers, so the
 *                          effective policy in production is the meta tag).
 *   2. app/csp-meta.ts   — the same CSP as a <meta http-equiv> constant,
 *                          rendered into <head> by app/layout.tsx. GitHub
 *                          Pages has no header mechanism; meta CSP is the
 *                          only enforcement surface available (documented in
 *                          docs/SECURITY_HEADERS.md).
 *
 * Runs on EVERY build — a stale hash would silently break theming; manual
 * hash entry is a BLOCKING failure.
 */
import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';

const src = readFileSync('app/theme-script.ts', 'utf8');
const m = src.match(/THEME_SCRIPT = `([^`]*)`;/);
if (!m) throw new Error('BLOCKING: THEME_SCRIPT template literal not found in app/theme-script.ts');

const script = m[1]
  .replace(/\\\`/g, '`')
  .replace(/\\\$/g, '$')
  .replace(/\\\\/g, '\\');

const hash = createHash('sha256').update(script, 'utf8').digest('base64');

const csp = [
  "default-src 'self'",
  `script-src 'self' 'sha256-${hash}'`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'self'",
  "form-action 'self'",
  "base-uri 'self'",
  "object-src 'none'",
  "frame-ancestors 'none'",
  'upgrade-insecure-requests',
].join('; ');

const headers = `# GENERATED by scripts/compute-csp-hash.mjs — do not edit the hash by hand.
# Regenerated on every build from the inline theme script in app/theme-script.ts (§3.4).
# NOTE: GitHub Pages does not serve custom HTTP headers. The ENFORCED policy on
# github-pages hosting is the <meta http-equiv="Content-Security-Policy"> emitted
# from app/csp-meta.ts. See docs/SECURITY_HEADERS.md.
/*
  Content-Security-Policy: ${csp}
  Strict-Transport-Security: max-age=63072000; includeSubDomains; preload
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), interest-cohort=()
  X-Frame-Options: DENY
`;

const metaTs = `// GENERATED by scripts/compute-csp-hash.mjs — do not edit by hand.
// Regenerated on every build from app/theme-script.ts (§3.4).
//
// GitHub Pages cannot serve custom HTTP headers, so the CSP is delivered via
// <meta http-equiv="Content-Security-Policy"> in <head> (app/layout.tsx).
// Meta-CSP limitations (vs header delivery): frame-ancestors and
// upgrade-insecure-requests are ignored by browsers in meta form; HSTS,
// X-Content-Type-Options, Referrer-Policy, Permissions-Policy and
// X-Frame-Options are header-only and therefore NOT enforceable on GitHub
// Pages. Full analysis: docs/SECURITY_HEADERS.md.

export const CSP_META = ${JSON.stringify(csp)};
`;

mkdirSync('public', {recursive: true});
writeFileSync('public/_headers', headers);
writeFileSync('app/csp-meta.ts', metaTs);
console.log(`CSP hash: sha256-${hash}`);
console.log('Wrote public/_headers + app/csp-meta.ts');
